import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { rateLimit } from 'express-rate-limit';
import { env } from './config/env.js';
import authRoutes from './routes/authRoutes.js';
import projectRoutes from './routes/projectRoutes.js';
import publicContentRoutes from './routes/publicContentRoutes.js';
import messageRoutes from './routes/messageRoutes.js';
import taskRoutes from './routes/taskRoutes.js';
import meetingRoutes from './routes/meetingRoutes.js';
import studentRoutes from './routes/studentRoutes.js';
import learningRoutes from './routes/learningRoutes.js';
import aiRoutes from './routes/aiRoutes.js';
import dashboardRoutes from './routes/dashboardRoutes.js';
import settingsRoutes from './routes/settingsRoutes.js';
import catalogRoutes from './routes/catalogRoutes.js';
import adminContentRoutes from './routes/adminContentRoutes.js';
import analyticsRoutes from './routes/analyticsRoutes.js';
import { errorHandler, notFound } from './middleware/errorHandler.js';
export const app=express();
app.set('trust proxy',1);app.use(helmet());app.use(cors({origin:env.CLIENT_URL,credentials:true}));app.use(express.json({limit:'1mb'}));app.use(cookieParser());
app.get('/api/health',(req,res)=>res.json({success:true,data:{status:'ok',service:'fahizhub-api'}}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:25,standardHeaders:'draft-8',legacyHeaders:false}),authRoutes);app.use('/api/projects',projectRoutes);app.use('/api/content',publicContentRoutes);app.use('/api/messages',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:'draft-8',legacyHeaders:false}),messageRoutes);app.use('/api/tasks',taskRoutes);app.use('/api/meetings',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:'draft-8',legacyHeaders:false}),meetingRoutes);app.use('/api/student',studentRoutes);app.use('/api/learning',learningRoutes);app.use('/api/ai',aiRoutes);app.use('/api/dashboard',dashboardRoutes);app.use('/api/settings',settingsRoutes);app.use('/api/catalog',catalogRoutes);app.use('/api/admin-content',adminContentRoutes);app.use('/api/analytics',rateLimit({windowMs:60*1000,limit:60,standardHeaders:'draft-8',legacyHeaders:false}),analyticsRoutes);app.use(notFound);app.use(errorHandler);
